declare_clippy_lint! {
    /// ### What it does
    /// Checks declarations and imports that give a primitive type's name to
    /// another item in the type namespace. This includes type parameters, modules,
    /// and names introduced by glob imports.
    ///
    /// Aliases that keep the same primitive in both type annotations and expression
    /// paths are allowed. Names of unstable primitives, such as `f16` and `f128`,
    /// are checked where those primitives are available.
    ///
    /// Standard modules named for their primitive, such as `std::str`
    /// and `std::f64`, can also be imported under their own names.
    ///
    /// The lint can also check unqualified names in the value namespace, such as
    /// free functions, parameters, and local variables. Checking declarations
    /// generated by external macros is a separate option.
    ///
    /// ### Why is this bad?
    /// Readers expect a name like `u8` to mean the built-in type. Shadowing it
    /// can cause surprising type errors or silently change the meaning of code.
    ///
    /// ### Known problems
    /// An external procedural macro can give a generated token the source location
    /// of an identically spelled input token. The lint may then report the binding
    /// even when `builtin-type-shadow-check-external-macros` is `false`. When
    /// checking generated local variables, the diagnostic can point to the input
    /// token whose location the macro reused.
    ///
    /// A local binding in an included expression also keeps its original source location.
    /// If local and externally generated `include!` calls share one expression and their
    /// bindings cannot be attributed to individual calls, local-only mode can miss a binding.
    /// Conversely, if a macro includes its own input file again and every enclosing expression
    /// keeps the original range, the lint can attribute the binding to its enclosing item.
    ///
    /// ### Example
    /// ```rust
    /// use core::primitive::u16 as u8;
    /// let value: u8 = 300;
    /// ```
    ///
    /// Use the actual type:
    /// ```rust
    /// let value: u16 = 300;
    /// ```
    #[clippy::version = "pre 1.29.0"]
    pub BUILTIN_TYPE_SHADOW,
    style,
    "shadowing a builtin type"
}

impl_lint_pass!(BuiltinTypeShadow => [BUILTIN_TYPE_SHADOW]);

pub struct BuiltinTypeShadow {
    check_values: bool,
    check_external_macros: bool,
    expanded_params: Option<NodeMap<ExpnId>>,
    generic_lists: NodeMap<Span>,
    glob_macro_uses: OnceLock<glob::MacroUses>,
    include_calls: Option<include::IncludeCalls>,
}

impl BuiltinTypeShadow {
    pub fn new(conf: &'static Conf) -> Self {
        Self {
            check_values: matches!(
                conf.builtin_type_shadow_scope,
                BuiltinTypeShadowScope::TypeAndValueNamespaces
            ),
            check_external_macros: conf.builtin_type_shadow_check_external_macros,
            expanded_params: None,
            generic_lists: NodeMap::default(),
            glob_macro_uses: OnceLock::new(),
            include_calls: None,
        }
    }

    fn diagnostic_span(
        &self,
        tcx: TyCtxt<'_>,
        span: Span,
        declaration: Span,
        defining_expn: ExpnId,
        source_token: impl FnOnce() -> Ident,
    ) -> Option<Span> {
        if span.desugaring_kind().is_some() {
            return None;
        }
        // A name can keep its caller's span while the declaration around it is generated.
        let mut expansions = Vec::new();
        for expanded in [declaration, span] {
            for call in macro_backtrace(expanded) {
                if !call.def_id.is_local() && !tcx.is_diagnostic_item(sym::include_macro, call.def_id) {
                    return self.check_external_macros.then(|| call.span.source_callsite());
                }
                expansions.push(call.expn);
            }
        }
        if defining_expn != ExpnId::root() {
            expansions.push(defining_expn);
        }
        binding_origin(tcx, expansions, Some(declaration), || {
            let token = source_token();
            ident_matches_source(tcx, token).then_some(token.span)
        })
        .report_span(span, self.check_external_macros)
    }

    fn check_res(&mut self, cx: &LateContext<'_>, name: Symbol, res: Res, span: Span, hir_id: HirId) -> bool {
        if !is_available_primitive(cx.tcx, name, span) {
            return false;
        }
        let namespace = match res {
            Res::Def(DefKind::ExternCrate, _) => Some(Namespace::TypeNS),
            _ => res.ns(),
        };
        let message = match namespace {
            Some(Namespace::TypeNS) if !primitive::preserves_name(cx, name, res) => {
                format!("this binding shadows the built-in type `{name}`")
            },
            Some(Namespace::ValueNS) if self.check_values => {
                format!("this value has the same name as the built-in type `{name}`")
            },
            _ => return false,
        };
        let declaration = cx.tcx.hir_span(hir_id);
        let source_token = || {
            // A glob has no written binding name. Check a token from the import itself.
            if let Some(tree) = use_tree(cx.tcx.hir_node(hir_id))
                && matches!(tree.kind, UseKind::Glob)
            {
                tree.prefix
                    .segments
                    .last()
                    .map_or(Ident::new(sym::asterisk, span), |segment| segment.ident)
            } else {
                Ident::new(name, span)
            }
        };
        let owner = cx.tcx.expn_that_defined(hir_id.owner);
        let mut included = None;
        if matches!(res, Res::Local(_)) && !span.from_expansion() && !declaration.from_expansion() {
            let matches = ident_matches_source(cx.tcx, Ident::new(name, span));
            // A proc macro can assign the pattern the span of an unrelated input token.
            if !matches && !self.check_external_macros {
                return false;
            }
            if let Some(enclosing) = include::enclosing_span(cx.tcx, hir_id, span) {
                included = self
                    .include_calls
                    .get_or_insert_with(|| include::IncludeCalls::collect(cx.tcx))
                    .origin(cx.tcx, enclosing, span, owner, matches);
            }
        }
        let report_span = match included {
            Some(origin) => origin.report_span(span, self.check_external_macros),
            None => self.diagnostic_span(cx.tcx, span, declaration, owner, source_token),
        };
        let Some(report_span) = report_span else { return false };
        span_lint_hir(cx, BUILTIN_TYPE_SHADOW, hir_id, report_span, message);
        true
    }

    fn check_use_tree(&mut self, cx: &LateContext<'_>, tree: &UseTree<'_>, hir_id: HirId) {
        match tree.kind {
            UseKind::Single(ident) => {
                // A unit struct, for example, imports both the type and its constructor.
                for res in [tree.prefix.res.type_ns, tree.prefix.res.value_ns]
                    .into_iter()
                    .flatten()
                {
                    if self.check_res(cx, ident.name, res, ident.span, hir_id) {
                        break;
                    }
                }
            },
            UseKind::Nested { items } => {
                for (tree, hir_id, _) in items {
                    self.check_use_tree(cx, tree, *hir_id);
                }
            },
            UseKind::Glob => {},
        }
    }
}

// Keep the generic diagnostic available even when type checking the body fails.
impl EarlyLintPass for BuiltinTypeShadow {
    fn check_generics(&mut self, _: &EarlyContext<'_>, generics: &Generics) {
        // A single identifier can be supplied to a macro that creates the parameter list.
        // Keep the brackets to distinguish it from a list supplied by the caller.
        for param in &generics.params {
            if PrimTy::from_name(param.ident.name).is_some() {
                self.generic_lists.insert(param.id, generics.span);
            }
        }
    }

    fn check_generic_param(&mut self, cx: &EarlyContext<'_>, param: &GenericParam) {
        let name = param.ident.name;
        if PrimTy::from_name(name).is_none() {
            return;
        }
        let declaration = self.generic_lists.remove(&param.id).unwrap_or_else(|| param.span());
        let message = match param.kind {
            GenericParamKind::Type { .. } => format!("this generic shadows the built-in type `{name}`"),
            GenericParamKind::Const { .. } if self.check_values => {
                format!("this value has the same name as the built-in type `{name}`")
            },
            _ => return,
        };
        ty::tls::with(|tcx| {
            if !is_available_primitive(tcx, name, param.ident.span) {
                return;
            }
            // Before HIR lowering, parameters have AST node IDs. Index expanded
            // parameters only if the crate has a candidate for this lint.
            let expanded_params = self.expanded_params.get_or_insert_with(|| {
                let resolutions = &tcx.resolutions(()).expn_that_defined;
                tcx.resolver_for_lowering()
                    .0
                    .borrow()
                    .owners
                    .items()
                    .flat_map(|(_, owner)| owner.node_id_to_def_id.items())
                    .filter_map(|(node, def_id)| {
                        let expansion = resolutions.get(def_id)?;
                        matches!(tcx.def_kind(*def_id), DefKind::TyParam | DefKind::ConstParam)
                            .then_some((*node, *expansion))
                    })
                    .collect()
            });
            let expansion = expanded_params.get(&param.id).copied().unwrap_or(ExpnId::root());
            if let Some(span) = self.diagnostic_span(tcx, param.ident.span, declaration, expansion, || param.ident) {
                span_lint(cx, BUILTIN_TYPE_SHADOW, span, message);
            }
        });
    }
}

impl<'tcx> LateLintPass<'tcx> for BuiltinTypeShadow {
    fn check_mod(&mut self, cx: &LateContext<'tcx>, module: &'tcx rustc_hir::Mod<'tcx>, id: LocalModId) {
        glob::check_mod(cx, module, id, self);
    }

    fn check_block(&mut self, cx: &LateContext<'tcx>, block: &'tcx rustc_hir::Block<'tcx>) {
        glob::check_block(cx, block, self);
    }

    fn check_item(&mut self, cx: &LateContext<'tcx>, item: &'tcx Item<'tcx>) {
        if let ItemKind::Use(tree) = &item.kind {
            self.check_use_tree(cx, tree, item.hir_id());
        } else if let Some(ident) = item.kind.ident()
            && PrimTy::from_name(ident.name).is_some()
        {
            let id = item.owner_id.to_def_id();
            self.check_res(
                cx,
                ident.name,
                Res::Def(cx.tcx.def_kind(id), id),
                ident.span,
                item.hir_id(),
            );
        }
    }

    fn check_foreign_item(&mut self, cx: &LateContext<'tcx>, item: &'tcx ForeignItem<'tcx>) {
        let id = item.owner_id.to_def_id();
        self.check_res(
            cx,
            item.ident.name,
            Res::Def(cx.tcx.def_kind(id), id),
            item.ident.span,
            item.hir_id(),
        );
    }

    fn check_pat(&mut self, cx: &LateContext<'tcx>, pat: &'tcx Pat<'tcx>) {
        if self.check_values
            && let PatKind::Binding(_, id, ident, _) = pat.kind
            && id == pat.hir_id
            // Async lowering reuses the original identifier in its synthetic parameter and move patterns.
            && !pat.span.is_desugaring(DesugaringKind::Async)
        {
            self.check_res(cx, ident.name, Res::Local(id), ident.span, pat.hir_id);
        }
    }
}

// Cache the origin of a group of include calls independently of the binding's span.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Origin {
    Local,
    External(Span),
    Mixed,
}

impl Origin {
    fn report_span(self, binding: Span, check_external: bool) -> Option<Span> {
        match self {
            Self::Local => Some(binding),
            Self::External(call) => check_external.then_some(call),
            Self::Mixed => check_external.then_some(binding),
        }
    }
}

// When a macro forwards a call, the declaration may be in another
// source file. Check the token that crossed the macro at this expansion edge.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
enum MacroInput {
    Binding,
    Invocation(ExpnId),
    Definition(ExpnId),
}

fn expansion_origin(tcx: TyCtxt<'_>, expansions: Vec<ExpnId>, binding: impl FnOnce() -> Option<Span>) -> Origin {
    binding_origin(tcx, expansions, None, binding)
}

fn binding_origin(
    tcx: TyCtxt<'_>,
    expansions: Vec<ExpnId>,
    declaration: Option<Span>,
    binding: impl FnOnce() -> Option<Span>,
) -> Origin {
    let binding = LazyCell::new(binding);
    let mut pending: Vec<_> = expansions.into_iter().map(|id| (id, MacroInput::Binding)).collect();
    // Follow both the invocation and the definition of a local helper. An external
    // macro may generate either of them, and they need not have the same origin.
    let mut seen = FxHashSet::default();
    while let Some((expansion, mut input)) = pending.pop() {
        if expansion == ExpnId::root() || !seen.insert((expansion, input)) {
            continue;
        }
        let origin = expansion.expn_data();
        if let Some(id) = origin.macro_def_id {
            if let Some(local) = id.as_local() {
                pending.push((tcx.expn_that_defined(local), MacroInput::Definition(expansion)));
            } else if !tcx.is_diagnostic_item(sym::include_macro, id) {
                // A bang macro can forward an argument through another macro. The
                // argument keeps its written span even if the wrapper lives in a template.
                let is_attribute = matches!(origin.kind, ExpnKind::Macro(MacroKind::Attr, _));
                let site = match input {
                    MacroInput::Binding => binding.and_then(|token| {
                        if let Some(decl) = declaration
                            && !is_attribute
                        {
                            (decl.ctxt() == token.ctxt() && decl.contains(token)).then_some(decl)
                        } else {
                            Some(token)
                        }
                    }),
                    MacroInput::Invocation(call) => macro_input_span(tcx, call, expansion, false),
                    MacroInput::Definition(call) => macro_input_span(tcx, call, expansion, true),
                };
                if let Some(site) = site {
                    if is_attribute {
                        pending.push((origin.parent, input));
                        continue;
                    }
                    if matches!(origin.kind, ExpnKind::Macro(MacroKind::Bang, _))
                        && let Some(parent) = argument_parent(expansion, site)
                    {
                        pending.push((parent, input));
                        continue;
                    }
                }
                return Origin::External(origin.call_site.source_callsite());
            }
        }
        if matches!(origin.kind, ExpnKind::Macro(MacroKind::Bang, _)) {
            input = MacroInput::Invocation(expansion);
        }
        pending.push((origin.parent, input));
    }
    Origin::Local
}

fn argument_parent(mut wrapper: ExpnId, argument: Span) -> Option<ExpnId> {
    while wrapper != ExpnId::root() {
        let data = wrapper.expn_data();
        if data.call_site.ctxt() == argument.ctxt() && data.call_site.contains(argument) {
            return Some(data.parent);
        }
        wrapper = data.parent;
    }
    None
}

fn has_mark(span: Span, expansion: ExpnId) -> bool {
    let mut ctxt = span.ctxt();
    while !ctxt.is_root() {
        if ctxt.remove_mark() == expansion {
            return true;
        }
    }
    false
}

fn macro_input_span(tcx: TyCtxt<'_>, call: ExpnId, expansion: ExpnId, definition: bool) -> Option<Span> {
    let call = call.expn_data();
    let span = if definition { call.def_site } else { call.call_site };
    if has_mark(span, expansion) {
        return None;
    }
    // A proc macro can also give its generated invocation or definition an unrelated
    // input span. Work from the expansion data so this check is available before HIR.
    span.check_text(tcx, |snippet| {
        let mut tokens = tokenize_with_text(snippet)
            .filter(|(kind, ..)| {
                !matches!(
                    kind,
                    TokenKind::Whitespace | TokenKind::LineComment { .. } | TokenKind::BlockComment { .. }
                )
            })
            .map(|(_, text, _)| text);
        if definition {
            let name = tcx.item_name(call.macro_def_id.unwrap());
            match tokens.find(|&token| matches!(token, "macro" | "macro_rules" | "{" | ";")) {
                Some("macro") => {},
                Some("macro_rules") if tokens.next() == Some("!") => {},
                _ => return false,
            }
            tokens.next().is_some_and(|token| {
                token.trim_start_matches("r#") == name.as_str() || span.from_expansion() && token == "$"
            })
        } else {
            let ExpnKind::Macro(MacroKind::Bang, path) = call.kind else {
                return false;
            };
            let name = path.as_str().rsplit("::").next().unwrap();
            let mut previous = None;
            let mut metavariable = false;
            for token in tokens {
                if token == "!" {
                    return previous == Some(name.trim_start_matches("r#")) || metavariable;
                }
                metavariable = span.from_expansion() && previous == Some("$");
                previous = Some(token.trim_start_matches("r#"));
            }
            false
        }
    })
    .then_some(span)
}

fn use_tree(node: Node<'_>) -> Option<&UseTree<'_>> {
    match node {
        Node::Item(Item {
            kind: ItemKind::Use(tree),
            ..
        })
        | Node::NestedUseTree(tree) => Some(tree),
        _ => None,
    }
}

fn ident_matches_source(tcx: TyCtxt<'_>, ident: Ident) -> bool {
    tcx.sess
        .source_map()
        .span_to_snippet(ident.span)
        .is_ok_and(|source| source.strip_prefix("r#").unwrap_or(&source) == ident.name.as_str())
}

fn is_available_primitive(tcx: TyCtxt<'_>, name: Symbol, span: Span) -> bool {
    match name {
        sym::f16 | sym::f128 => tcx.features().enabled(name) || span.allows_unstable(name),
        _ => PrimTy::from_name(name).is_some(),
    }
}
